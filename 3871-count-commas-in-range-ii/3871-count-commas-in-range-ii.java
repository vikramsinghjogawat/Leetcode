class Solution {
    public long countCommas(long n) {
        // 1 to 999     -0 each
        // 1,000 to 999,999 -1 each
        // 1,000,000 to 999,999,999 -2 each
        // 1,000,000,000 to 999,999,999,999- 3 each
        // 1,000,000,000,000 to 999,999,999,999,999 - 4 each
        
        
        
        
        Long s1=0l;
        if(n==1000000000000000l){
            s1=5l;
            n=999999999999999l;
        }
        if(n>=1000000000000l && n<=999999999999999l) {
            s1=s1+(n-1000000000000l+1)*4;
            n=999999999999l;
        }
        if(n>=1000000000l &&n<=999999999999l){ 
            s1= s1+ (n-1000000000l+1)*3;
            n=999999999l;
        }
        if(n>=1000000l && n<=999999999l){ 
            s1=s1+ (n-1000000l+1)*2;
            n=999999l;
        }
        if(n>=1000l &&n<=999999l){ 
            s1=s1+(n-1000l+1);
        }
        
        
        
        
        
        return s1;


    }
}